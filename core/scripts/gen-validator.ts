// Compile spec/schema/humans.schema.json (owned by S1) into a standalone validator: no eval at runtime,
// so it runs on Workers. The server, the skills' CLI and the tests all validate with S1's schema itself.
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { unicodeSchema } from "../../spec/tools/unicode17.mjs";
import { readerSchema } from "../../spec/tools/reader-core.mjs";

const root = join(import.meta.dirname, "..");
const schema = unicodeSchema(JSON.parse(readFileSync(join(root, "../spec/schema/humans.schema.json"), "utf8")));
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv, ["date", "uuid"]);

// AJV's output still calls require() for three runtime helpers, and CommonJS interop differs between
// Node, Vite and esbuild. Inline them instead, so the module has no imports and runs anywhere.
const HELPERS: Record<string, string> = {
  'require("ajv/dist/runtime/ucs2length").default':
    "((s) => { let n = 0; for (const _ of s) n++; return n; })",
  'require("ajv/dist/runtime/equal").default':
    "((a, b) => JSON.stringify(a) === JSON.stringify(b))",
  // ajv-formats exposes `date` as { validate, compare }; only validate is called.
  'require("ajv-formats/dist/formats").fullFormats.date':
    '({ validate: (s) => { const m = /^(\\d{4})-(\\d{2})-(\\d{2})$/.exec(s); if (!m) return false; const d = new Date(0); d.setUTCFullYear(+m[1], +m[2] - 1, +m[3]); return d.getUTCFullYear() === +m[1] && d.getUTCMonth() === +m[2] - 1 && d.getUTCDate() === +m[3]; } })',
};
mkdirSync(join(root, "src/generated"), { recursive: true });
const readSchema = readerSchema(schema);
delete readSchema.$id;
for (const [name, definition] of [["profile", schema], ["reader", readSchema]] as const) {
  const validate = ajv.compile(definition);
  let code = standalone(ajv, validate);
  for (const [call, inline] of Object.entries(HELPERS)) code = code.split(call).join(inline);
  const left = code.match(/require\([^)]*\)[.\w]*/gu);
  if (left) throw new Error(`unhandled runtime helper(s): ${left.join(", ")}`);
  writeFileSync(join(root, `src/generated/validate-${name}.js`), `// Generated by scripts/gen-validator.ts from spec/schema/humans.schema.json. Do not edit.\n${code}`);
  writeFileSync(join(root, `src/generated/validate-${name}.d.ts`), "// Generated by scripts/gen-validator.ts. Do not edit.\ndeclare const validate: ((value: unknown) => boolean) & { errors?: unknown[] | null };\nexport default validate;\n");
  console.log(`validator: generated ${name} from spec/schema/humans.schema.json`);

}
