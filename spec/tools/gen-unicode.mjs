// Regenerate the schema's Unicode category check using a Unicode 17.0 runtime.
// The generated ranges make validation independent of the consumer's ICU version.
import { writeFileSync } from 'node:fs';
import { readJson } from './lib.mjs';
if (process.versions.unicode !== '17.0') throw new Error('UNICODE_17_GENERATOR_REQUIRED');
const rule = new RegExp(readJson('schema/humans.schema.json').$defs.unsafeText.anyOf[0].pattern,'u');
const ranges = [];
let start;
/** Format a code point as a hexadecimal Unicode escape for the generated regular expression. */
const cp = n => `\\u{${n.toString(16)}}`;
for (let n = 0; n <= 0x110000; n++) {
  const bad = n < 0x110000 && rule.test(String.fromCodePoint(n));
  if (bad && start === undefined) start = n;
  if (!bad && start !== undefined) { ranges.push(start === n - 1 ? cp(start) : `${cp(start)}-${cp(n-1)}`); start = undefined; }
}
const pattern = `[${ranges.join('')}]`;
writeFileSync(new URL('./unicode17.mjs',import.meta.url), `// Generated by gen-unicode.mjs on Unicode 17.0. Do not edit.\nexport const unsafeUnicodePattern = ${JSON.stringify(pattern)};\nexport function unicodeSchema(schema) {\n  const copy = structuredClone(schema);\n  copy.$defs.unsafeText.anyOf[0].pattern = unsafeUnicodePattern;\n  return copy;\n}\n`);
writeFileSync(new URL('./unicode17.d.mts',import.meta.url), '// Generated by gen-unicode.mjs. Do not edit.\nexport const unsafeUnicodePattern: string;\nexport function unicodeSchema<T>(schema: T): T;\n');
console.log(`Unicode 17.0: generated ${ranges.length} unsafe ranges`);
